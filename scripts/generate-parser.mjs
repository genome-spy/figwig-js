import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { fileURLToPath, URL } from 'node:url'
import process from 'node:process'
import console from 'node:console'
import { build } from 'esbuild'
import compiler from 'kaitai-struct-compiler'
import YAML from 'yaml'

const root = fileURLToPath(new URL('../', import.meta.url))
const schemaText = await readFile(
  new URL('../schema/figwig.ksy', import.meta.url),
  'utf8',
)
const schemaHash = createHash('sha256').update(schemaText).digest('hex')
const files = await compiler.compile(
  'javascript',
  YAML.parse(schemaText),
  null,
  false,
)
const generated = files['Figwig.js']
const start = generated.indexOf('var Figwig = (function() {')
const footer = '\nFigwig_.Figwig = Figwig;\n});\n'
if (start < 0 || !generated.endsWith(footer)) {
  throw new Error(
    'Unexpected Kaitai output wrapper; inspect compiler changes before regenerating',
  )
}
// Change only the module wrapper. All binary field readers come from the compiler.
const parser = generated.slice(start, -footer.length)
const banner = `// @ts-nocheck\n// Generated by Kaitai Struct ${compiler.version}; do not edit.\n// Source: schema/figwig.ksy (sha256 ${schemaHash}).\n// Schema adapted from Figwig, Copyright (c) 2026 Jacob Schreiber, MIT.\n`
const parserText = `${banner}import KaitaiStream from './runtime.js'\n\n${parser}\nexport default Figwig\n`

// The official UMD runtime has optional Node zlib and legacy iconv hooks.
// Figwig uses its own bounded inflater and modern TextDecoder on both platforms.
// Bundle the unmodified runtime with explicit unavailable-feature modules so
// ordinary consumer bundlers require no Node aliases or polyfills.
const runtime = await build({
  absWorkingDir: root,
  stdin: {
    contents:
      "import Runtime from 'kaitai-struct/KaitaiStream.js'; export default Runtime",
    resolveDir: root,
    sourcefile: 'kaitai-runtime-entry.js',
  },
  bundle: true,
  platform: 'browser',
  target: 'es2022',
  format: 'esm',
  legalComments: 'inline',
  write: false,
  plugins: [
    {
      name: 'unused-node-hooks',
      setup(builder) {
        builder.onResolve({ filter: /^(?:zlib|iconv-lite)$/ }, (args) => ({
          path: args.path,
          namespace: 'unused-node-hooks',
        }))
        builder.onLoad(
          { filter: /.*/, namespace: 'unused-node-hooks' },
          () => ({
            contents:
              'throw new Error("Kaitai optional Node hooks are unavailable; use Figwig bounded decoding")',
            loader: 'js',
          }),
        )
      },
    },
  ],
})
const runtimeText =
  '// @ts-nocheck\n// Generated portable ESM bundle of kaitai-struct 0.11.0; do not edit.\n// Copyright 2012-2016 Ilmari Heikkinen; 2016-2025 Kaitai Project.\n// Apache-2.0; see LICENSES/kaitai-runtime.txt.\n' +
  runtime.outputFiles[0].text
const output = new URL('../src/kaitai/generated/', import.meta.url)
await mkdir(output, { recursive: true })
const artifacts = [
  ['figwig.ts', parserText],
  ['runtime.ts', runtimeText],
]
if (process.argv.includes('--check')) {
  for (const [name, contents] of artifacts) {
    if ((await readFile(new URL(name, output), 'utf8')) !== contents) {
      throw new Error(
        `${name} differs from pinned parser generation; run npm run parser:generate`,
      )
    }
  }
  console.log('Generated Kaitai parser and runtime are up to date')
} else {
  for (const [name, contents] of artifacts)
    await writeFile(new URL(name, output), contents)
  console.log('Generated Kaitai parser and portable runtime')
}
